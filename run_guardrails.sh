#!/bin/bash
set -e

cd /home/ak/projects/doc_processor_service/traceability_service

echo "=========================================================="
echo "Starting TraceabilityService Performance Guardrail Workflow"
echo "=========================================================="

echo "Step 1: Building TraceabilityService.slnx..."
dotnet build TraceabilityService.slnx --configuration Debug

echo "Step 2: Creating local ./coverage directory..."
mkdir -p /home/ak/projects/doc_processor_service/traceability_service/coverage

echo "Step 3: Running dotCover cover snapshot generation with assembly filter..."
dotCover cover --target-working-directory /home/ak/projects/doc_processor_service/traceability_service --snapshot-output /home/ak/projects/doc_processor_service/traceability_service/coverage/report.dcvr --filters=+:TraceabilityService -- test /home/ak/projects/doc_processor_service/traceability_service/TraceabilityService.slnx

# Sync snapshot file generated by dotCover Linux CLI into ./coverage/
python3 -c "
import os, shutil
def safe_copy(src, dst):
    src_abs = os.path.abspath(src)
    dst_abs = os.path.abspath(dst)
    if os.path.exists(src_abs) and src_abs != dst_abs:
        os.makedirs(os.path.dirname(dst_abs), exist_ok=True)
        shutil.copyfile(src_abs, dst_abs)

target_dir = '/home/ak/projects/doc_processor_service/traceability_service/coverage'
for root, dirs, files in os.walk('/home/ak/projects/doc_processor_service/traceability_service'):
    for f in files:
        if 'report.dcvr' in f:
            safe_copy(os.path.join(root, f), os.path.join(target_dir, 'report.dcvr'))
" 2>/dev/null || true

echo "Step 4: Running dotCover report for HTML dashboard generation..."
dotCover report --source=/home/ak/projects/doc_processor_service/traceability_service/coverage/report.dcvr --output=/home/ak/projects/doc_processor_service/traceability_service/coverage/CoverageReport.html --reportType=HTML 2>/dev/null || dotCover report --snapshot-source /home/ak/projects/doc_processor_service/traceability_service/coverage/report.dcvr --html-report-output /home/ak/projects/doc_processor_service/traceability_service/coverage/CoverageReport.html 2>/dev/null || true

echo "Step 5: Running dotCover report for DetailedXML generation..."
dotCover report --source=/home/ak/projects/doc_processor_service/traceability_service/coverage/report.dcvr --output=/home/ak/projects/doc_processor_service/traceability_service/coverage/CoverageReport.xml --reportType=DetailedXML 2>/dev/null || dotCover report --snapshot-source /home/ak/projects/doc_processor_service/traceability_service/coverage/report.dcvr --xml-report-output /home/ak/projects/doc_processor_service/traceability_service/coverage/CoverageReport.xml 2>/dev/null || true

# Sync report files generated by dotCover Linux CLI into ./coverage/ (including backslash path normalization)
python3 -c "
import os, shutil
def safe_copy(src, dst):
    src_abs = os.path.abspath(src)
    dst_abs = os.path.abspath(dst)
    if os.path.exists(src_abs) and src_abs != dst_abs:
        os.makedirs(os.path.dirname(dst_abs), exist_ok=True)
        shutil.copyfile(src_abs, dst_abs)

target_dir = '/home/ak/projects/doc_processor_service/traceability_service/coverage'
for root, dirs, files in os.walk('/home/ak/projects/doc_processor_service/traceability_service'):
    for f in files:
        if 'report.dcvr' in f:
            safe_copy(os.path.join(root, f), os.path.join(target_dir, 'report.dcvr'))
        if 'CoverageReport.xml' in f:
            safe_copy(os.path.join(root, f), os.path.join(target_dir, 'CoverageReport.xml'))
        if 'CoverageReport.html' in f:
            safe_copy(os.path.join(root, f), os.path.join(target_dir, 'CoverageReport.html'))
" 2>/dev/null || true

echo "=========================================================="
echo "Step 6: Verifying coverage report files in ./coverage/"
echo "=========================================================="
ls -lh /home/ak/projects/doc_processor_service/traceability_service/coverage/report.dcvr /home/ak/projects/doc_processor_service/traceability_service/coverage/CoverageReport.xml /home/ak/projects/doc_processor_service/traceability_service/coverage/CoverageReport.html

echo "Workflow completed successfully!"
